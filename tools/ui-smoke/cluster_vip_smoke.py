def cluster_vip_ui(pg, ctx):
    out = lambda n: os.path.join(args.out, n)
    produced = []
    api = lambda path, data=None, method="POST": pg.evaluate(API, ["./api/cluster/vip/" + path, data or {}, method])

    def theme(want_dark):
        if pg.evaluate("document.body.classList.contains('darkTheme')") != want_dark:
            pg.evaluate("toggleTheme()")
            pg.wait_for_timeout(300)

    def clear_toasts():
        pg.evaluate("document.querySelectorAll('.zx-toast').forEach(e => e.remove())")

    def toast(pattern):
        pg.wait_for_function("p => [...document.querySelectorAll('.zx-toast')].some(e => new RegExp(p, 'i').test(e.innerText))", arg=pattern, timeout=8000)
        clear_toasts()

    def layout(label):
        """one scroller (the page), nothing leaves its card, code wraps"""
        check_horizontal(pg, label)
        bad = pg.evaluate("""() => {
            const msgs = [], page = document.getElementById('clusterPage');
            page.querySelectorAll('*').forEach(e => {
                if (e.offsetParent === null) return;
                const cs = getComputedStyle(e);
                if (/(auto|scroll)/.test(cs.overflowY) && e.scrollHeight > e.clientHeight + 1) msgs.push('nested scroll area: ' + (e.id || e.className));
            });
            page.querySelectorAll('#vipWrap .zx-codeblock, #vipWrap .zx-codeblock pre').forEach(e => {
                if (e.offsetParent !== null && e.scrollWidth > e.clientWidth + 1) msgs.push('a code block scrolls sideways: ' + (e.id || e.className));
            });
            document.querySelectorAll('#vipWrap .zx-card').forEach(card => {
                if (card.offsetParent === null) return;
                const cr = card.getBoundingClientRect();
                card.querySelectorAll('.zx-callout, .zx-codeblock, .vipTopo__box, .vipMember, .vipCheck, .zx-btn, .zx-input, .zx-select, .zx-badge, table, dd').forEach(el => {
                    if (el.offsetParent === null) return;
                    const r = el.getBoundingClientRect();
                    if (r.width && (r.left < cr.left - 1 || r.right > cr.right + 1)) msgs.push((el.id || el.className) + ' leaves its card: ' + Math.round(r.left) + '..' + Math.round(r.right) + ' vs ' + Math.round(cr.left) + '..' + Math.round(cr.right));
                });
            });
            return [...new Set(msgs)];
        }""")
        for m in bad:
            fail("layout", f"{label}: {m}")

    def shots(name, variants=(("light", False, 1366), ("dark", True, 1366), ("390", False, 390))):
        for label, dark, w in variants:
            theme(dark)
            pg.set_viewport_size({"width": w, "height": 900})
            pg.wait_for_timeout(400)
            clear_toasts()
            layout(f"{name}/{label}")
            pg.locator("#vipWrap").screenshot(path=out(f"cluster-vip-{name}-{label}.png"))
            produced.append(f"cluster-vip-{name}-{label}.png")
        theme(False)
        pg.set_viewport_size({"width": 1366, "height": 900})
        pg.wait_for_timeout(300)

    def visible(sel):
        return pg.locator(sel).first.is_visible()

    def text(sel):
        return " ".join(pg.inner_text(sel).split())

    # the interface list of the page is answered with a placeholder host: 192.0.2.11/24 on ens18
    nics = [{"Name": "lo", "ID": 1, "IPs": ["127.0.0.1/8", "::1/128"]}, {"Name": "ens18", "ID": 2, "IPs": ["192.0.2.11/24", "fe80::1/64"]}]
    pg.route("**/api/stats/listnic", lambda r: r.fulfill(status=200, content_type="application/json", body=json.dumps(nics)))

    def reload():
        pg.evaluate("ClusterPage.reload()")
        settle(pg, 700)

    theme(False)
    pg.set_viewport_size({"width": 1366, "height": 900})
    try:
        _cluster_vip_body(pg, ctx, api, shots, layout, toast, clear_toasts, visible, text, reload, out)
        produced.append("cluster-vip-active-1920.png")
        # every picture of the scenario has to exist: light, dark, wide and phone
        want = ["cluster-vip-off-light.png", "cluster-vip-off-dark.png", "cluster-vip-off-390.png", "cluster-vip-setup-light.png", "cluster-vip-blocked-light.png",
                "cluster-vip-active-light.png", "cluster-vip-active-dark.png", "cluster-vip-active-390.png", "cluster-vip-active-1920.png",
                "cluster-vip-conf-390-dark.png", "cluster-vip-standby-light.png", "cluster-vip-stale-light.png",
                "cluster-vip-split-light.png", "cluster-vip-split-dark.png", "cluster-vip-split-390.png", "cluster-vip-follower-light.png", "cluster-vip-follower-390.png"]
        for n in want:
            if n not in produced or not os.path.exists(out(n)) or os.path.getsize(out(n)) < 2000:
                fail("cluster-vip", f"screenshot missing: {n}")
    except Exception as ex:   # a step that timed out is a failure of that step, not a crashed run
        fail("cluster-vip", f"scenario aborted: {' '.join(str(ex).split()[:40])}")
        pg.screenshot(path=out("cluster-vip-failure.png"), full_page=True)
    for pat in ("**/api/stats/listnic", "**/api/cluster/vip/**"):
        pg.unroute(pat)
    # leave the instance quiet: saved settings may stay (a throw-away instance), but switched off
    cfg = api("config", method="GET")
    if isinstance(cfg, dict) and cfg.get("exists") and cfg["shared"].get("enabled"):
        s = {k: v for k, v in cfg["shared"].items() if k not in ("passwordSet", "password")}
        s["enabled"] = False
        api("shared", {"config": json.dumps(s)})
    theme(False)
    pg.set_viewport_size({"width": 1366, "height": 800})
    pg.evaluate("window.ClusterPage && ClusterPage.reload()")
    settle(pg, 400)


