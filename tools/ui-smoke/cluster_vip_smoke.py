    if "systemctl disable --now keepalived" not in pg.inner_text(".zx-dialog"):
        fail("cluster-vip", "the switch-off question must say that keepalived keeps running and how to stop it")
    pg.click(".zx-dialog [data-zx-ok]")
    toast("switched off")
    pg.wait_for_selector("#vipKept", state="visible", timeout=6000)
    cfg = api("config", method="GET")
