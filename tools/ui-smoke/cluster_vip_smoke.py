"""Smoke scenario of the Floating IP section of Cluster / HA: the simple guided setup (docs/cluster/vip-simple-setup.md). exec()'d by
smoke.py (namespace: fail, current, args, os, re, settle, check_horizontal); run alone with --cluster-vip-only on a throw-away instance.

Part 1, against the REAL instance (a standalone node without a cluster secret): the page title, the off state, the guided setup
(Before you start, the main/backup cards with mouse and keyboard, the floating IP with suggestions and warnings, the DHCP tick), a
field error from the server next to its field, a real save (main server stored, password made by the server and never shown), the
"this server is not one of the servers" state with one script card per server, a field error of the server-local values, and
switching off again ("settings kept"). The interface list and the address suggestions are ALWAYS answered by mocks, so the pictures
hold placeholder addresses only and the smoke never probes the real network.

Part 2, with every floating IP route answered by a fixture (a host that really holds a floating IP cannot be had in a smoke run):
waiting, one server running, both running, the guided test with its timeline, failover happened, split brain, nobody answers, keeps
moving, each card state, a blocked health check and a follower.

In every state: no horizontal overflow, nothing leaves its card, NO nested scroll area, no code block that scrolls, the firewall
step exactly once, no shield icon, no "Configuration for" dropdown, no tabs, and none of the expert words (priority, VRRP, ...) on
the main path. Screenshots (light and dark at 1366px, 390px, 1920px) go to --out as cluster-vip-*.png.

All addresses are placeholders (192.0.2.0/24, 203.0.113.0/24). Nothing here touches keepalived or the host network."""

