    if pw in pg.evaluate("document.getElementById('vipWrap').innerText"):
        fail("cluster-vip", "the saved VRRP password must not be shown on the page while the configuration is blocked")
    levels = pg.eval_on_selector_all("#vipChecks .vipCheck", "els => els.map(e => [e.dataset.id, e.dataset.level, e.querySelector('.zx-badge').innerText.trim()])")
    if not any(l[1] == "ok" and l[2] == "Passed" for l in levels) or not any(l[0] == "member" and l[1] == "block" and l[2] == "Has to be fixed" for l in levels):
        fail("cluster-vip", f"the pre-flight list must have pass rows and a blocking 'this node' row on this host: {levels}")
    if "to fix" not in text("#vipStep2Badge") or "to fix before the configuration can be written" not in text("#vipCheckSum"):
        fail("cluster-vip", f"the result of the checks must be summed up: {text('#vipStep2Badge')!r} / {text('#vipCheckSum')!r}")
    pg.wait_for_selector("#vipBlocked", state="visible", timeout=6000)
