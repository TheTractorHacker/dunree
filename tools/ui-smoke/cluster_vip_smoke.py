"""Smoke scenario of the Floating IP section of Cluster / HA (docs/cluster/vip-plan.md section 8). exec()'d by smoke.py (namespace:
fail, current, args, os, re, settle, check_horizontal); run alone with --cluster-vip-only on a throw-away instance.

Part 1, against the REAL instance (a standalone node without a cluster secret): the page title, no "deprecated" wording, the off
state, the guided setup with the form pre-filled from the host's interfaces (the interface list is answered by a mock so the
pictures and the test hold placeholder addresses only), the live hints, a field error from the server next to its field, a real
save, the real pre-flight list (this host is not one of the placeholder nodes, so a check has to block), the blocked install step,
a field error of the node-local values, and switching off again ("settings kept").

Part 2, with the four floating IP routes answered by mocks (a host that really holds a floating IP cannot be had in a smoke run):
active on this node as a primary with a follower, the generated keepalived.conf and the commands (copy, download link, tabs),
standby, split brain, a follower (shared settings read-only) and keepalived not installed.

Layout in every state: no horizontal overflow, nothing leaves its card, NO nested scroll area inside the page and no code block
that scrolls. Screenshots (light and dark at 1366px, 390px, 1920px) go to --out as cluster-vip-*.png.

All addresses are placeholders (192.0.2.0/24, 203.0.113.0/24). Nothing here touches keepalived or the host network."""

