def vip_script(label, addr, role):
    """the installer as the server would make it, shortened: first line and password are what the page is checked against"""
    return ("# Dunree floating IP installer for %s (%s) - %s\n# Paste all of this into a terminal ON %s. It asks for your sudo password if needed.\n"
            "if [ \"$(id -u)\" = 0 ]; then sh -s\nelif command -v sudo >/dev/null 2>&1; then sudo sh -s\nelse echo \"Dunree: please log in as root (type: su -) and paste this again.\"; cat >/dev/null\n"
            "fi <<'DUNREE_SETUP_END'\nset -eu\nD_LABEL='%s'\nD_ROLE='%s'\nD_ADDR='%s'\n# ... the rest of the installer ...\nDUNREE_SETUP_END\n") % (label, addr, role, label, label, role, addr)


def cluster_vip_ui(pg, ctx):
    out = lambda n: os.path.join(args.out, n)
    produced = []
    api = lambda path, data=None, method="POST": pg.evaluate(API, ["./api/cluster/vip/" + path, data or {}, method])

    def theme(want_dark):
        if pg.evaluate("document.body.classList.contains('darkTheme')") != want_dark:
            pg.evaluate("toggleTheme()")
            pg.wait_for_timeout(300)

    def clear_toasts():
        pg.evaluate("document.querySelectorAll('.zx-toast').forEach(e => e.remove())")

    def toast(pattern):
        pg.wait_for_function("p => [...document.querySelectorAll('.zx-toast')].some(e => new RegExp(p, 'i').test(e.innerText))", arg=pattern, timeout=8000)
        clear_toasts()

    def layout(label):
        """one scroller (the page), nothing leaves its card, code wraps; and the rules of the redesign that hold in EVERY state"""
        check_horizontal(pg, label)
        bad = pg.evaluate("""(expert) => {
            const msgs = [], page = document.getElementById('clusterPage'), wrap = document.getElementById('vipWrap');
            const shown = e => e.offsetParent !== null;
            page.querySelectorAll('*').forEach(e => {
                if (!shown(e)) return;
                const cs = getComputedStyle(e);
                if (/(auto|scroll)/.test(cs.overflowY) && e.scrollHeight > e.clientHeight + 1) msgs.push('nested scroll area: ' + (e.id || e.className));
            });
            wrap.querySelectorAll('.zx-codeblock, .zx-codeblock pre, .vipCmd code').forEach(e => {
                if (shown(e) && e.scrollWidth > e.clientWidth + 1) msgs.push('a code block scrolls sideways: ' + (e.id || e.className));
            });
            wrap.querySelectorAll('.zx-card, .vipNext').forEach(card => {
                if (!shown(card)) return;
                const cr = card.getBoundingClientRect();
                card.querySelectorAll('.zx-callout, .zx-codeblock, .vipTopo__box, .vipNode, .vipPick__item, .vipCheck, .vipCmd, .vipTick, .vipResult, .zx-btn, .zx-input, .zx-select, .zx-badge, table, dd, h3, h4, p').forEach(el => {
                    if (!shown(el)) return;
                    const r = el.getBoundingClientRect();
                    if (r.width && (r.left < cr.left - 1 || r.right > cr.right + 1)) msgs.push((el.id || el.className || el.tagName) + ' leaves its card: ' + Math.round(r.left) + '..' + Math.round(r.right) + ' vs ' + Math.round(cr.left) + '..' + Math.round(cr.right));
                });
            });
            // a button next to a heading is as high as the heading row (the old "Copy commands" button was taller than its heading)
            wrap.querySelectorAll('.vipCodeHead').forEach(h => {
                if (!shown(h)) return;
                const label = h.querySelector('span'), btn = h.querySelector('.zx-btn');
                if (!btn || !label) return;
                const lr = label.getBoundingClientRect(), br = btn.getBoundingClientRect();
                if (Math.abs(lr.top - br.top) < 4 && Math.abs(lr.height - br.height) > 2) msgs.push('a copy button is not as high as its heading: ' + Math.round(br.height) + ' vs ' + Math.round(lr.height));
            });
            if (wrap.querySelector('i.shield.icon, i.icon.shield')) msgs.push('a shield icon is back in the floating IP section');
            if (wrap.querySelector('#vipGenFor, .zx-tabs, .zx-tab')) msgs.push('the "Configuration for" dropdown or the tabs are back');
            if (/Configuration for/.test(wrap.textContent)) msgs.push('the words "Configuration for" are back');
            const fw = [...wrap.querySelectorAll('h3, h4, .zx-callout__title')].filter(e => /firewall/i.test(e.textContent));
            if (document.getElementById('vipFlow').hidden ? fw.length !== 1 : fw.length !== 1 || !shown(fw[0])) msgs.push('the firewall step must be there exactly once, found ' + fw.length);
            // the main path: everything visible that is not inside a <details>, a help popover or a field of the form
            const clone = wrap.cloneNode(true);
            wrap.querySelectorAll('*').forEach((e, i) => { if (!shown(e) && e.tagName !== 'OPTION') e.setAttribute('data-gone', '1'); });
            const live = wrap.cloneNode(true);
            wrap.querySelectorAll('[data-gone]').forEach(e => e.removeAttribute('data-gone'));
            live.querySelectorAll('[data-gone], details, .zx-popover, pre, code').forEach(e => e.remove());
            const m = new RegExp(expert).exec(live.textContent);
            if (m) msgs.push('an expert word is on the main path: ' + m[0]);
            return [...new Set(msgs)];
        }""", VIP_EXPERT)
        for m in bad:
            fail("layout", f"{label}: {m}")

    def shots(name, variants=(("light", False, 1366), ("dark", True, 1366), ("390", False, 390))):
        for label, dark, w in variants:
            theme(dark)
            pg.set_viewport_size({"width": w, "height": 1000 if w > 1500 else 900})
            pg.wait_for_timeout(400)
            clear_toasts()
            layout(f"{name}/{label}")
            pg.locator("#vipWrap").screenshot(path=out(f"cluster-vip-{name}-{label}.png"))
            produced.append(f"cluster-vip-{name}-{label}.png")
        theme(False)
        pg.set_viewport_size({"width": 1366, "height": 900})
        pg.wait_for_timeout(300)

    def visible(sel):
        return pg.locator(sel).first.is_visible()

    def text(sel):
        return " ".join(pg.inner_text(sel).split())

    # the interface list of the page is answered with a placeholder host: 192.0.2.11/24 on ens18. The suggestions are answered by a
    # fixture in BOTH parts: the real endpoint would probe addresses of the network this machine is in.
    nics = [{"Name": "lo", "ID": 1, "IPs": ["127.0.0.1/8", "::1/128"]}, {"Name": "ens18", "ID": 2, "IPs": ["192.0.2.11/24", "fe80::1/64"]}]
    pg.route("**/api/stats/listnic", lambda r: r.fulfill(status=200, content_type="application/json", body=json.dumps(nics)))
    pg.route("**/api/cluster/vip/suggest", lambda r: r.fulfill(status=200, content_type="application/json", body=json.dumps(VIP_SUGGEST)))

    def reload():
        pg.evaluate("ClusterPage.reload()")
        settle(pg, 700)

    theme(False)
    pg.set_viewport_size({"width": 1366, "height": 900})
    want = []
    try:
        pg.evaluate("Object.keys(localStorage).filter(k => k.indexOf('dunree.vip.') === 0).forEach(k => localStorage.removeItem(k))")
        _cluster_vip_body(pg, ctx, api, shots, layout, toast, clear_toasts, visible, text, reload, out, want)
        # every picture of the scenario has to exist: light, dark, wide and phone
        for n in want:
            if n not in produced or not os.path.exists(out(n)) or os.path.getsize(out(n)) < 2000:
                fail("cluster-vip", f"screenshot missing: {n}")
    except Exception as ex:   # a step that timed out is a failure of that step, not a crashed run
        fail("cluster-vip", f"scenario aborted: {' '.join(str(ex).split()[:40])}")
        pg.screenshot(path=out("cluster-vip-failure.png"), full_page=True)
    for pat in ("**/api/stats/listnic", "**/api/cluster/vip/suggest", "**/api/cluster/vip/**"):
        pg.unroute(pat)
    # leave the instance quiet: saved settings may stay (a throw-away instance), but switched off
    cfg = api("config", method="GET")
    if isinstance(cfg, dict) and cfg.get("exists") and cfg["shared"].get("enabled"):
        s = {k: v for k, v in cfg["shared"].items() if k not in ("passwordSet", "password", "clusterPassSet")}
        s["enabled"] = False
        api("shared", {"config": json.dumps(s)})
    pg.evaluate("Object.keys(localStorage).filter(k => k.indexOf('dunree.vip.') === 0).forEach(k => localStorage.removeItem(k))")
    theme(False)
    pg.set_viewport_size({"width": 1366, "height": 800})
    pg.evaluate("window.ClusterPage && (ClusterPage.pageHost = '', ClusterPage.reload())")
    settle(pg, 400)


def _cluster_vip_body(pg, ctx, api, shots, layout, toast, clear_toasts, visible, text, reload, out, want):
    banner = lambda: text("#vipNextSay")
    before = lambda: pg.eval_on_selector_all("#vipBeforeList .vipCheck", "els => els.map(e => [e.dataset.id, e.dataset.level, e.querySelector('.vipCheck__say').innerText.replace(/\\s+/g, ' ').trim()])")
    picks = lambda: pg.eval_on_selector_all("#vipPick .vipPick__item", "els => els.map(e => [e.getAttribute('aria-checked'), e.innerText.replace(/\\s+/g, ' ').trim()])")

    def wait_banner(pattern, ms=12000):
        try:
            pg.wait_for_function("p => new RegExp(p).test(document.getElementById('vipNextSay').innerText) && !document.getElementById('vipNext').hidden", arg=pattern, timeout=ms)
        except Exception:
            fail("cluster-vip", f"the Next step banner must say /{pattern}/, it says {banner()!r}")

    # ================= part 1: the real instance =================
    current["page"] = "cluster-vip/off"
    pg.evaluate("openTabById('cluster')")
    settle(pg, 1200)
    reload()
    if pg.inner_text("#clusterPage .zx-page-header__title").strip() != "Cluster / HA":
        fail("cluster-vip", "the page title must stay 'Cluster / HA'")
    if re.search(r"deprecat", pg.evaluate("document.getElementById('cluster').textContent"), re.I):
        fail("cluster-vip", "nothing on Cluster / HA may say deprecated")
    cfg = api("config", method="GET")
    if cfg.get("exists") or cfg["shared"].get("enabled"):
        fail("cluster-vip", f"a fresh instance must have no floating IP settings and the feature off: {cfg.get('exists')}, {cfg['shared'].get('enabled')}")
    host = cfg.get("nodeName") or ""
    if not host:
        fail("cluster-vip", "the config answer must carry this server's host name (the default name of this server)")
    own = re.sub(r"^[^A-Za-z0-9]+", "", re.sub(r"[^A-Za-z0-9._-]+", "-", host.split(".")[0]))[:32] or "server-1"
    other = "server-1" if own == "server-2" else "server-2"
    if pg.get_attribute("#vipCard", "data-vip-state") != "new" or not visible("#vipSetupBtn") or visible("#vipFlow") or visible("#vipNext"):
        fail("cluster-vip", "off state: the card must show the call to action and nothing of the setup")
    if "Not set up" not in text("#vipBadge") or "Off by default" not in text("#vipDesc") or "whichever server is healthy answers on it" not in text("#vipDesc"):
        fail("cluster-vip", f"off state: badge / the two sentences are wrong: {text('#vipBadge')!r} / {text('#vipDesc')!r}")
    if pg.locator("#vipTopo .vipTopo__box").count() != 4 or "Main server" not in text("#vipTopo") or "Backup server" not in text("#vipTopo"):
        fail("cluster-vip", "off state: the picture (router, floating IP, main and backup server) must show")
    if "Not set up" not in text("#clFacts"):
        fail("cluster-vip", "the status card of the page must carry the floating IP fact")
    if visible("#vipOnBtn") or visible("#vipOffBtn") or visible("#vipKept"):
        fail("cluster-vip", "off state: no on / off buttons and no 'settings kept' note before the first save")
    shots("off")
    want += ["cluster-vip-off-light.png", "cluster-vip-off-dark.png", "cluster-vip-off-390.png"]

    # ---- not ready: the setup opens, Dunree fills in what it knows and says what is missing ----
    current["page"] = "cluster-vip/notready"
    pg.click("#vipSetupBtn")
    pg.wait_for_selector("#vipIpForm", state="visible", timeout=4000)
    pg.wait_for_selector("#vipSugChips [data-vip-sug]", state="visible", timeout=6000)
    rows = before()
    if not any(r[0] == "self" and r[1] == "ok" and f"This server: {own} (192.0.2.11)" in r[2] for r in rows):
        fail("cluster-vip", f"Before you start must name this server by its host name and address: {rows}")
    if not any(r[0] == "peer" and r[1] == "warn" for r in rows) or pg.locator("#vipBeforeList [data-id=peer] .zx-btn").count() != 1:
        fail("cluster-vip", f"Before you start must ask for the other server with one button: {rows}")
    if not any(r[0] == "linked" and r[1] == "info" and "Optional" in r[2] and "already inside" in r[2] for r in rows):
        fail("cluster-vip", f"linking must be optional and must say that the password is already in the scripts: {rows}")
    if "0 of" in text("#vipBeforeCount") or "1 of 2 done" not in text("#vipBeforeCount"):
        fail("cluster-vip", f"the count of Before you start is wrong: {text('#vipBeforeCount')!r}")
    if "other server" not in banner() or pg.get_attribute("#vipNext", "data-kind") != "todo" or not visible("#vipNextBtn"):
        fail("cluster-vip", f"not ready: the banner must ask for the other server's address, with one button: {banner()!r}")
    p = picks()
    if len(p) != 2 or p[0][0] != "true" or own not in p[0][1] or "You are here" not in p[0][1] or "MAIN SERVER" not in p[0][1].upper() or "BACKUP SERVER" not in p[1][1].upper() or "192.0.2.11" not in p[0][1]:
        fail("cluster-vip", f"step 1 must show one card per server, this one as main and marked 'You are here': {p}")
    if pg.get_attribute("#vipPick", "role") != "radiogroup" or pg.locator("#vipPick [role=radio]").count() != 2:
        fail("cluster-vip", "the server cards must be a radio group")
    for n in (3, 4, 5):
        if "is-dim" not in (pg.get_attribute(f"#vipStep{n}", "class") or "") or pg.get_attribute(f"#vipStep{n}", "aria-disabled") != "true" or "Finish step" not in text(f"#vipStep{n}"):
            fail("cluster-vip", f"step {n} must be dimmed and say which step comes first")
    if visible("#vipNodes .vipNode") or visible("#vipTestBtn") or visible("#vipFwTick"):
        fail("cluster-vip", "a dimmed step must not offer its controls")
    auth = pg.evaluate("document.getElementById('vipAuth').textContent")
    if pg.input_value("#vipPrefixIn") != "24" or pg.input_value("#vipAuth") != "auto" or "Automatic (made for you)" not in auth or re.search(r"cluster", auth, re.I):
        fail("cluster-vip", "under Show details: the prefix comes from this server, the password is 'Automatic (made for you)' and never says cluster")
    shots("notready")
    want += ["cluster-vip-notready-light.png", "cluster-vip-notready-dark.png", "cluster-vip-notready-390.png"]
    # the button of the banner takes the user to the field
    pg.click("#vipNextBtn")
    if pg.evaluate("document.activeElement.id") != "vipS1address":
        fail("cluster-vip", "the banner's button must focus the address field of the other server")
    pg.keyboard.type("192.0.2.12")
    if "192.0.2.12" not in picks()[1][1] or "Pick a spare address" not in banner():
        fail("cluster-vip", f"typing the other server's address must fill its card and move the banner on: {picks()} / {banner()!r}")
    if f"{own} is the main server. Click {other} to change that." not in text("#vipMainSay"):
        fail("cluster-vip", f"step 1 must say who is main and how to change it: {text('#vipMainSay')!r}")
    # main / backup by keyboard, then by mouse
    pg.focus("#vipPick .vipPick__item[aria-checked=true]")
    pg.keyboard.press("ArrowRight")
    p = picks()
    if p[1][0] != "true" or "MAIN SERVER" not in p[1][1].upper() or "BACKUP SERVER" not in p[0][1].upper() or f"{other} is the main server" not in text("#vipMainSay"):
        fail("cluster-vip", f"the arrow key must make the other server the main server: {p}")
    if pg.evaluate("document.activeElement.getAttribute('data-i')") != "1":
        fail("cluster-vip", "after the arrow key the focus must be on the chosen card")
    pg.keyboard.press("ArrowLeft")
    pg.click("#vipPick .vipPick__item[data-i='1']")
    if picks()[1][0] != "true":
        fail("cluster-vip", "a click must choose the main server")
    pg.focus("#vipPick .vipPick__item[data-i='0']")
    pg.keyboard.press("Space")
    if picks()[0][0] != "true" or pg.input_value("#vipS0priority") != "150" or pg.input_value("#vipS1priority") != "100":
        fail("cluster-vip", "Space must choose the card, and the numbers under Show details must follow (150 / 100)")
    # the floating IP: suggestions, the network in words, warnings in plain words
    if pg.locator("#vipSugChips [data-vip-sug]").count() != 3 or "Likely free, not proven" not in text("#vipSug"):
        fail("cluster-vip", "step 2 must offer three suggestions and say that they are not proven")
    if "Your network: 192.0.2.0 to 192.0.2.255" not in text("#vipNetLine"):
        fail("cluster-vip", f"step 2 must say the network in words: {text('#vipNetLine')!r}")
    pg.fill("#vipAddrIn", "192.0.2.12")
    if f"address of {other} itself" not in text("#vipAddrHint"):
        fail("cluster-vip", f"a server's own address as floating IP must be turned down in plain words: {text('#vipAddrHint')!r}")
    pg.fill("#vipAddrIn", "198.51.100.9")
    if "198.51.100.9 is not in your network (192.0.2.0 to 192.0.2.255)" not in text("#vipAddrHint"):
        fail("cluster-vip", f"an address outside the network must be turned down in plain words: {text('#vipAddrHint')!r}")
    pg.fill("#vipAddrIn", "192.0.2.1")
    if "router's address" not in text("#vipAddrHint"):
        fail("cluster-vip", "the router's address must be turned down")
    pg.click("#vipSugChips [data-vip-sug='192.0.2.10']")
    if pg.input_value("#vipAddrIn") != "192.0.2.10" or visible("#vipAddrHint") or "192.0.2.10" not in text("#vipTopo"):
        fail("cluster-vip", "a suggestion must fill the field and the picture")
    wait_banner("Check that 192\\.0\\.2\\.10 is outside your router's DHCP range")
    # saving without the tick: asked for in place, nothing stored
    pg.click("#vipSaveBtn")
    if not visible("#vipTickErr") or api("config", method="GET").get("exists"):
        fail("cluster-vip", "saving without the DHCP tick must ask for it and store nothing")
    pg.click("#vipTickRow .zx-whatis")
    if not visible("#vipDhcpWhat") or "UniFi" not in text("#vipDhcpWhat"):
        fail("cluster-vip", "the ? next to the tick must say where the DHCP range is found")
    pg.click("#vipTickRow .zx-whatis")
    pg.check("#vipDhcpTick")
    if visible("#vipTickErr"):
        fail("cluster-vip", "ticking must take the reminder away")
    pg.fill("#vipAddrIn", "192.0.2.20")
    if pg.is_checked("#vipDhcpTick"):
        fail("cluster-vip", "changing the address must clear the tick")
    pg.fill("#vipAddrIn", "192.0.2.10")
    pg.check("#vipDhcpTick")
    # the server refuses a name, and the reason appears next to the field
    pg.fill("#vipS1label", "bad/name")
    pg.click("#vipSaveBtn")
    pg.wait_for_selector("#vipServers .zx-field.is-invalid .zx-error", state="visible", timeout=6000)
    if pg.get_attribute("#vipS1label", "aria-invalid") != "true" or api("config", method="GET").get("exists"):
        fail("cluster-vip", "a name the server refuses must be marked at its field, and nothing stored")
    clear_toasts()
    pg.fill("#vipS1label", other)
    if visible("#vipFlow .zx-field.is-invalid"):
        fail("cluster-vip", "correcting the form must take the field error away")

    # this smoke host cannot ask the placeholder servers what their network card is called: typed under Show details, as the card would ask
    pg.click("#vipDetails > summary")
    pg.fill("#vipS0interfaceHint", "ens18")
    pg.fill("#vipS1interfaceHint", "ens18")
    pg.click("#vipDetails > summary")

    # ---- ready: everything is filled in, the banner says save ----
    current["page"] = "cluster-vip/ready"
